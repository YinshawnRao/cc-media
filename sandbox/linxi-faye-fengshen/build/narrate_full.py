out = Path("audio_full"); out.mkdir(exist_ok=True)
pipe = KPipeline(lang_code="z")
durs = {}
for k, t in LINES.items():
    chunks = [a for _, _, a in pipe(t, voice=VOICE, speed=1.0)]
    audio = chunks[0] if len(chunks) == 1 else np.concatenate(chunks)
    sf.write(out / f"{k}.wav", audio, SR)
    durs[k] = round(len(audio) / SR, 3)
    print(f"{k}: {durs[k]}s")
print("lines:", len(durs), "total voice:", round(sum(durs.values()), 1), "s")
import json
Path("audio_full/durs.json").write_text(json.dumps(durs, ensure_ascii=False, indent=1), encoding="utf-8")
