#!/usr/bin/env python3
"""林俊杰综艺翻唱 TOP5 — 旁白配音（女声 zf_xiaoyi，倒数盘点）。
段：intro + 5 首倒数(voice s5->s1) + outro。副歌展示段无旁白(纯音乐)，收束用屏幕金句。
开头不剧透排名；倒数口播"第五…第一"(排名播报,允许)；outro 排名靠画面揭晓，旁白做情感收束。
铁律：无英文/字母混读(Kokoro 不擅长)——FIR→飞儿乐团、CD/TOP 一律不入口播；无 meta 文案。
"""
import json
from pathlib import Path
import numpy as np
import soundfile as sf
from kokoro import KPipeline

VOICE = "zf_xiaoyi"   # 女声（brief 要求女性配音）
SR = 24000
SPEED = 0.96          # 稍慢，盘点/纪录片感

BLOCKS = {
    # 开场：立题"行走的现场 / 综艺翻唱天花板"，不剧透名次
    "intro": "在《梦想的声音》的舞台上，有一个名字，几乎成了翻唱的天花板，林俊杰。别人的歌到了他手里，常常被重新长出另一种样子，音准稳得像录音室，高音却又能层层炸开。今天这五首，都是他在综艺里翻唱别人的封神现场。听完你也许会承认，有些歌，真的怕被他翻唱。",

    # 05 我们的爱 飞儿乐团（梦声2）——摇滚燃点
    "s5": "第五名，飞儿乐团的《我们的爱》。原版是女声的空灵和爆发，到了林俊杰手里，被他唱成了一场摇滚现场。副歌一句比一句往上顶，真假音来回切换，高音几乎不要钱地往外砸。它是那种一开口，就能把全场点燃、听完整个人都上头的现场。",

    # 04 末班车 萧煌奇（梦声1）——中国风改编 + 现场掌控
    "s4": "第四名，萧煌奇的《末班车》。这首歌本来就难唱，林俊杰却给它加了一层中国风的编曲。前半段他收着嗓子，像在低声讲一个告别的故事；后半段高音猛地推开，离别的情绪一下子被拉满。它不是最热门的那一条，但最能看出，他对一首歌的理解，和现场的掌控力。",

    # 03 不能说的秘密 周杰伦（梦声3）——改得很林俊杰
    "s3": "第三名，周杰伦的《不能说的秘密》。难的不是唱周杰伦，而是他改得很有自己的味道，古典的底子、大提琴、吉他，还悄悄穿插进了一段《星晴》。一首青春电影的主题曲，被他重新编成了一台华丽的舞台作品。两家的歌迷，大概会在评论区，聊上很久。",

    # 02 我怀念的 孙燕姿（梦声1）——林氏重塑
    "s2": "第二名，孙燕姿的《我怀念的》。这是很典型的一次林氏重塑。孙燕姿的原版，是撕裂，是倔强；林俊杰这一版，更像很多年以后回头再看，把那份痛唱得格外克制，后劲却一点点漫上来。他不是要抢原唱的位置，更像在旁边，又开了一家分店。",

    # 01 输了你赢了世界又如何 优客李林/林志炫（梦声2）——压轴
    "s1": "第一名，《输了你赢了世界又如何》，原唱是优客李林。这首必须排第一，是林俊杰综艺翻唱里，最破圈的一版。他的高音不是硬顶上去，而是一层一层往上推，情绪、气息、混声、爆发力，全部在线。那一句，输了你，赢了全世界又能如何，被他唱出了整个世界崩塌的感觉。听过的人，大多会记很久。",

    # 结尾：排名靠画面揭晓，旁白做情感收束
    "outro": "把这五首放在一起你会发现，林俊杰最厉害的，从来不只是音准和高音。他是真的把每一首别人的歌，重新理解了一遍，再唱成只属于他的版本。也许下一次，当你又听到这几首歌的原版，会忽然想起，有个人曾在综艺的舞台上，把它们，唱进了很多人的心里。",
}

pipeline = KPipeline(lang_code="z")
Path("audio").mkdir(exist_ok=True)
meta = {}
for key, text in BLOCKS.items():
    chunks = [a for _, _, a in pipeline(text, voice=VOICE, speed=SPEED)]
    audio = chunks[0] if len(chunks) == 1 else np.concatenate(chunks)
    sf.write(f"audio/{key}.wav", audio, SR)
    meta[key] = {"text": text, "dur": round(len(audio) / SR, 3)}
    print(f"{key:8s} {meta[key]['dur']:6.2f}s")

Path("narration.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
print("TOTAL narration", round(sum(m["dur"] for m in meta.values()), 2), "s")
