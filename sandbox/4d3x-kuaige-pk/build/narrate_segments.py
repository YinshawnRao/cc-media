def synth(name, text):
    out = OUT / f"{name}.wav"
    cmd = [str(TTS), str(NARR), text, "--voice", VOICE, "-o", str(out)]
    print(f"[{name}] {text[:40]}...")
    subprocess.run(cmd, check=True)
    return out

if __name__ == "__main__":
    only = sys.argv[1:] or list(BLOCKS.keys())
    for k in only:
        synth(k, BLOCKS[k])
    print(f"\nDone. {len(only)} wavs in {OUT}")
